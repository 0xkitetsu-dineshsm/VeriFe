#!/usr/bin/env python3
"""Turn an eth_getProof fixture into a Fe module.

    python3 tools/mpt_to_fe.py fixtures/mpt/mpt_mainnet.json

A proof is emitted as the RLP list of its node encodings, which is what
`mpt::lookup` walks and what the Solidity verifiers take as `bytes[]`.
Keccak comes from `cast keccak`, so the trie keys in the generated module are
not this script's idea of keccak256.
"""
import json, subprocess, sys
from pathlib import Path

def keccak(data: bytes) -> str:
    out = subprocess.run(["cast", "keccak", "0x" + data.hex()],
                         capture_output=True, text=True, check=True)
    return out.stdout.strip()

# `fe test` deploys the whole EVM test suite as one contract, so these byte
# arrays count against the 24,576-byte EIP-170 limit -- and four
# execution-layer fixtures do not fit beside the SSZ ones. The verifier itself
# is backend-independent (`mpt::lookup` is the same code either way); what is
# EVM-specific is the hasher, and `hash.fe`'s `both_byte_hashers_agree` covers
# that on the EVM target with no fixture data at all. See docs/fe-findings.md.
GATE = '#[cfg(target = "native")]'


def gate_consts(text: str) -> str:
    """Put the native gate in front of every `pub const` in generated text."""
    out = []
    for line in text.splitlines(keepends=True):
        if line.startswith("pub const "):
            out.append(GATE + "\n")
        out.append(line)
    return "".join(out)


# The same fixture, UNGATED, for the `evm_mpt_tests` ingot.
#
# `fe test` deploys each ingot's suite as its own contract, so a second ingot
# gets its own 24,576-byte EIP-170 budget -- which is how real mainnet proofs
# reach the EVM target at all. Emitting both copies from one JSON means they
# cannot drift; `./check.sh` regenerates and diffs them byte for byte.
EVM_INGOT = Path("evm_mpt_tests/src")


def also_emit_ungated(src: Path, text: str) -> Path:
    """Write the same module without the native gate, for the EVM-target ingot."""
    EVM_INGOT.mkdir(parents=True, exist_ok=True)
    out = EVM_INGOT / f"fixture_{src.stem}.fe"
    # `fe_array` embeds the gate ahead of each `pub fn`, so stripping it from
    # the whole text is what makes this copy usable on the EVM target.
    ungated = "".join(l for l in text.splitlines(keepends=True) if l.strip() != GATE)
    out.write_text(ungated)
    return out


def rlp_len(n: int, short: int, long: int) -> bytes:
    if n <= 55:
        return bytes([short + n])
    be = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([long + len(be)]) + be

def rlp_str(b: bytes) -> bytes:
    if len(b) == 1 and b[0] < 0x80:
        return b
    return rlp_len(len(b), 0x80, 0xb7) + b

def rlp_list(items) -> bytes:
    body = b"".join(items)
    return rlp_len(len(body), 0xc0, 0xf7) + body

def proof_bytes(nodes) -> bytes:
    return rlp_list([rlp_str(bytes.fromhex(n[2:])) for n in nodes])

def fe_array(name: str, data: bytes, doc: str) -> str:
    rows = []
    for i in range(0, len(data), 12):
        rows.append("        " + ", ".join("0x%02x" % x for x in data[i:i+12]) + ",")
    return (f"{doc}\n{GATE}\npub fn {name}() -> MemBuffer {{\n"
            f"    let bytes: [u8; {len(data)}] = [\n" + "\n".join(rows) +
            "\n    ]\n    var buf = MemBuffer::new(0)\n"
            "    for byte in bytes {\n        buf.push(byte)\n    }\n    buf\n}\n")

def emit_receipt(src: Path, d: dict) -> Path:
    """The receipts-trie fixture: a proof of one receipt, and its logs."""
    p = d["provenance"]
    r = d["receipt"]
    key = bytes.fromhex(r["key"][2:])
    nodes = [bytes.fromhex(n[2:]) for n in r["proof"]]
    parts = [f'''//! A real mainnet receipt proof, and the logs it commits to.
//!
//! Generated by `tools/mpt_to_fe.py` from `{src.name}`. There is no RPC that
//! serves a receipt proof, so `tools/gen_receipt_fixture.mjs` rebuilt the
//! block's receipts trie from its {p["receipt_count"]} receipts and read a
//! proof out of it -- and that rebuild was accepted only because it hashes to
//! the `receiptsRoot` in the block header, exactly as the period rebuild must
//! hash to the `block_summary_root` the anchor state commits to.
//!
//! The builder is JavaScript and VeriFe's verifier is Fe, so these are two
//! independent implementations checked against data neither wrote.
//!
//! Provenance
//! ----------
//!   endpoint      {p["execution_rpc"]}
//!   block         {p["block_number"]:,}
//!   block hash    {p["block_hash"]}
//!   receipts root {p["receipts_root"]}
//!   receipts      {p["receipt_count"]}
//!   proved        transaction {r["tx_index"]} ({r["tx_hash"]})

use core::ptr::MemBuffer

/// The block, and the receipts-trie root VeriFe proves as
/// `ExecutionPayload.receipts_root`.
pub const BLOCK_NUMBER: u64 = {p["block_number"]}
pub const RECEIPTS_ROOT: u256 = {p["receipts_root"]}

/// The transaction whose receipt is proved, and its trie key.
///
/// The receipts trie keys by `rlp(index)` **unhashed**, so this key is
/// {len(key)} byte(s) and not 32. That is why `mpt::lookup` takes a key
/// length.
pub const TX_INDEX: u64 = {r["tx_index"]}
pub const KEY_LEN: usize = {len(key)}
pub const RECEIPT_TYPE: u8 = {int(r["type"], 16)}
pub const RECEIPT_STATUS: u256 = {int(r["status"], 16)}
pub const CUMULATIVE_GAS_USED: u256 = {int(r["cumulative_gas_used"], 16)}
pub const LOG_COUNT: usize = {len(r["logs"])}
''']
    parts.append(fe_array("key", key, "/// `rlp(%d)`, the trie key." % r["tx_index"]))
    parts.append(fe_array("proof", proof_bytes(r["proof"]),
        f"/// The {len(nodes)}-node proof, as an RLP list of node encodings."))
    for i, log in enumerate(r["logs"]):
        addr = bytes.fromhex(log["address"][2:])
        data = bytes.fromhex(log["data"][2:]) if log["data"] != "0x" else b""
        parts.append(f'''
/// Log {i}: {len(log["topics"])} topics, {len(data)} bytes of data.
pub const LOG_{i}_ADDRESS: u256 = 0x{addr.hex()}
pub const LOG_{i}_TOPIC_COUNT: usize = {len(log["topics"])}
pub const LOG_{i}_DATA_LEN: usize = {len(data)}
''')
        for t, topic in enumerate(log["topics"]):
            parts.append(f"pub const LOG_{i}_TOPIC_{t}: u256 = {topic}\n")
    text = "".join(parts)
    out = Path(f"verife/src/fixture_{src.stem}.fe")
    out.write_text(gate_consts(text))
    also_emit_ungated(src, text)
    return out


src = Path(sys.argv[1])
d = json.loads(src.read_text())
schema = d.get("schema")
if schema == "verife-receipt-fixture-1":
    print("wrote", emit_receipt(src, d))
    sys.exit(0)
if schema != "verife-mpt-fixture-1":
    # Each generator owns its own schema, so `for f in fixtures/mpt/*.json`
    # does not have to know which tool to call.
    print(f"skip {src.name}: schema {schema!r} belongs to another generator")
    sys.exit(0)
p = d["provenance"]
usdc = d["cases"]["usdc"]
pr = usdc["proof"]
addr = bytes.fromhex(usdc["address"][2:])

parts = [f'''//! Real mainnet Merkle-Patricia proofs, from `eth_getProof`.
//!
//! Generated by `tools/mpt_to_fe.py` from `{src.name}`. Nothing here is
//! synthetic: the nodes are the ones a mainnet node served for block
//! {p["block_number"]:,}, and the values are what it reported for the same
//! keys, so the tests that use them are differential tests against geth's own
//! trie rather than against our reading of the spec.
//!
//! Provenance
//! ----------
//!   endpoint      {p["execution_rpc"]}
//!   method        {p["method"]}
//!   block         {p["block_number"]:,}
//!   block hash    {p["block_hash"]}
//!   state root    {p["state_root"]}
//!
//! The state root here is the block header's own. Joining it to a
//! *beacon-proven* state root needs a fixture whose EIP-4788 anchor is still
//! inside the 27.3 h window -- see `docs/forward-compat.md`.

use core::ptr::MemBuffer

/// The block these proofs were taken at.
pub const BLOCK_NUMBER: u64 = {p["block_number"]}

/// The state trie root they are rooted at: this block's `stateRoot`.
pub const STATE_ROOT: u256 = {p["state_root"]}

/// USDC's address, and the state-trie key it hashes to.
pub const ACCOUNT: u256 = 0x{addr.hex()}
pub const ACCOUNT_KEY: u256 = {keccak(addr)}

/// What the node reported for that account.
pub const ACCOUNT_NONCE: u256 = {int(pr["nonce"], 16)}
pub const ACCOUNT_BALANCE: u256 = {int(pr["balance"], 16)}
pub const ACCOUNT_STORAGE_ROOT: u256 = {pr["storageHash"]}
pub const ACCOUNT_CODE_HASH: u256 = {pr["codeHash"]}
''']

parts.append(fe_array("account_proof", proof_bytes(pr["accountProof"]),
    f"/// The {len(pr['accountProof'])}-node account proof, as an RLP list of node encodings."))

# The same proof with its final node removed. A verifier that reads a short
# proof as "absent" rather than refusing it is the March 2025 bug class; this
# is what the negative test needs.
parts.append(fe_array("account_proof_truncated", proof_bytes(pr["accountProof"][:-1]),
    f"/// The same proof with its last node removed: {len(pr['accountProof']) - 1} of "
    f"{len(pr['accountProof'])}. Must be refused, never read as absent."))

# The same proof with the root node appended a second time. Every node in a
# proof must be used, or the same fact has two encodings -- and malleability
# becomes somebody's soundness bug once a proof's hash is stored or signed.
parts.append(fe_array("account_proof_with_extra_node",
    proof_bytes(pr["accountProof"] + [pr["accountProof"][0]]),
    f"/// The same proof with a {len(pr['accountProof']) + 1}th node that the path "
    f"never reaches. Must be refused."))

for i, sp in enumerate(pr["storageProof"]):
    slot = bytes.fromhex(sp["key"][2:].rjust(64, "0"))
    val = int(sp["value"], 16)
    label = "present" if val != 0 else "absent"
    parts.append(f'''
/// Storage slot {sp["key"]} -- {label} in USDC's storage trie.
pub const SLOT_{i}: u256 = 0x{slot.hex()}
pub const SLOT_{i}_KEY: u256 = {keccak(slot)}
pub const SLOT_{i}_VALUE: u256 = {val}
pub const SLOT_{i}_PRESENT: bool = {"true" if val != 0 else "false"}
''')
    parts.append(fe_array(f"slot_{i}_proof", proof_bytes(sp["proof"]),
        f"/// Its {len(sp['proof'])}-node storage proof."))

if "absent_account" in d["cases"]:
    dead = d["cases"]["absent_account"]
    dpr = dead["proof"]
    daddr = bytes.fromhex(dead["address"][2:])
    parts.append(f'''
    /// An account with no storage at all: its `storageRoot` is the empty-trie
    /// root, which is how `hash.fe`'s `EMPTY_TRIE_ROOT` is cross-checked against
    /// the chain rather than against a constant we typed.
    pub const EOA: u256 = 0x{daddr.hex()}
    pub const EOA_KEY: u256 = {keccak(daddr)}
    pub const EOA_STORAGE_ROOT: u256 = {dpr["storageHash"]}
    pub const EOA_NONCE: u256 = {int(dpr["nonce"], 16)}
    ''')
    parts.append(fe_array("eoa_proof", proof_bytes(dpr["accountProof"]),
        f"/// Its {len(dpr['accountProof'])}-node account proof."))

# One module per source file, named after it, so a second fixture does not
# silently overwrite the first.
text = "".join(parts)
out = Path(f"verife/src/fixture_{src.stem}.fe")
out.write_text(gate_consts(text))
print("wrote", out)
print("wrote", also_emit_ungated(src, text))
