#!/usr/bin/env python3
"""Turn an eth_getProof fixture into a Fe module.

    python3 tools/mpt_to_fe.py fixtures/mpt/mpt_mainnet.json

A proof is emitted as the RLP list of its node encodings, which is what
`mpt::lookup` walks and what the Solidity verifiers take as `bytes[]`.
Keccak comes from `cast keccak`, so the trie keys in the generated module are
not this script's idea of keccak256.
"""
import json, subprocess, sys
from pathlib import Path

def keccak(data: bytes) -> str:
    out = subprocess.run(["cast", "keccak", "0x" + data.hex()],
                         capture_output=True, text=True, check=True)
    return out.stdout.strip()

def rlp_len(n: int, short: int, long: int) -> bytes:
    if n <= 55:
        return bytes([short + n])
    be = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([long + len(be)]) + be

def rlp_str(b: bytes) -> bytes:
    if len(b) == 1 and b[0] < 0x80:
        return b
    return rlp_len(len(b), 0x80, 0xb7) + b

def rlp_list(items) -> bytes:
    body = b"".join(items)
    return rlp_len(len(body), 0xc0, 0xf7) + body

def proof_bytes(nodes) -> bytes:
    return rlp_list([rlp_str(bytes.fromhex(n[2:])) for n in nodes])

def fe_array(name: str, data: bytes, doc: str) -> str:
    rows = []
    for i in range(0, len(data), 12):
        rows.append("        " + ", ".join("0x%02x" % x for x in data[i:i+12]) + ",")
    return (f"{doc}\npub fn {name}() -> MemBuffer {{\n"
            f"    let bytes: [u8; {len(data)}] = [\n" + "\n".join(rows) +
            "\n    ]\n    var buf = MemBuffer::new(0)\n"
            "    for byte in bytes {\n        buf.push(byte)\n    }\n    buf\n}\n")

src = Path(sys.argv[1])
d = json.loads(src.read_text())
p = d["provenance"]
usdc = d["cases"]["usdc"]
pr = usdc["proof"]
addr = bytes.fromhex(usdc["address"][2:])

parts = [f'''//! Real mainnet Merkle-Patricia proofs, from `eth_getProof`.
//!
//! Generated by `tools/mpt_to_fe.py` from `{src.name}`. Nothing here is
//! synthetic: the nodes are the ones a mainnet node served for block
//! {p["block_number"]:,}, and the values are what it reported for the same
//! keys, so the tests that use them are differential tests against geth's own
//! trie rather than against our reading of the spec.
//!
//! Provenance
//! ----------
//!   endpoint      {p["execution_rpc"]}
//!   method        {p["method"]}
//!   block         {p["block_number"]:,}
//!   block hash    {p["block_hash"]}
//!   state root    {p["state_root"]}
//!
//! The state root here is the block header's own. Joining it to a
//! *beacon-proven* state root needs a fixture whose EIP-4788 anchor is still
//! inside the 27.3 h window -- see `docs/forward-compat.md`.

use core::ptr::MemBuffer

/// The block these proofs were taken at.
pub const BLOCK_NUMBER: u64 = {p["block_number"]}

/// The state trie root they are rooted at: this block's `stateRoot`.
pub const STATE_ROOT: u256 = {p["state_root"]}

/// USDC's address, and the state-trie key it hashes to.
pub const ACCOUNT: u256 = 0x{addr.hex()}
pub const ACCOUNT_KEY: u256 = {keccak(addr)}

/// What the node reported for that account.
pub const ACCOUNT_NONCE: u256 = {int(pr["nonce"], 16)}
pub const ACCOUNT_BALANCE: u256 = {int(pr["balance"], 16)}
pub const ACCOUNT_STORAGE_ROOT: u256 = {pr["storageHash"]}
pub const ACCOUNT_CODE_HASH: u256 = {pr["codeHash"]}
''']

parts.append(fe_array("account_proof", proof_bytes(pr["accountProof"]),
    f"/// The {len(pr['accountProof'])}-node account proof, as an RLP list of node encodings."))

# The same proof with its final node removed. A verifier that reads a short
# proof as "absent" rather than refusing it is the March 2025 bug class; this
# is what the negative test needs.
parts.append(fe_array("account_proof_truncated", proof_bytes(pr["accountProof"][:-1]),
    f"/// The same proof with its last node removed: {len(pr['accountProof']) - 1} of "
    f"{len(pr['accountProof'])}. Must be refused, never read as absent."))

for i, sp in enumerate(pr["storageProof"]):
    slot = bytes.fromhex(sp["key"][2:].rjust(64, "0"))
    val = int(sp["value"], 16)
    label = "present" if val != 0 else "absent"
    parts.append(f'''
/// Storage slot {sp["key"]} -- {label} in USDC's storage trie.
pub const SLOT_{i}: u256 = 0x{slot.hex()}
pub const SLOT_{i}_KEY: u256 = {keccak(slot)}
pub const SLOT_{i}_VALUE: u256 = {val}
pub const SLOT_{i}_PRESENT: bool = {"true" if val != 0 else "false"}
''')
    parts.append(fe_array(f"slot_{i}_proof", proof_bytes(sp["proof"]),
        f"/// Its {len(sp['proof'])}-node storage proof."))

dead = d["cases"]["absent_account"]
dpr = dead["proof"]
daddr = bytes.fromhex(dead["address"][2:])
parts.append(f'''
/// An account with no storage at all: its `storageRoot` is the empty-trie
/// root, which is how `hash.fe`'s `EMPTY_TRIE_ROOT` is cross-checked against
/// the chain rather than against a constant we typed.
pub const EOA: u256 = 0x{daddr.hex()}
pub const EOA_KEY: u256 = {keccak(daddr)}
pub const EOA_STORAGE_ROOT: u256 = {dpr["storageHash"]}
pub const EOA_NONCE: u256 = {int(dpr["nonce"], 16)}
''')
parts.append(fe_array("eoa_proof", proof_bytes(dpr["accountProof"]),
    f"/// Its {len(dpr['accountProof'])}-node account proof."))

out = Path("verife/src/fixture_mpt_mainnet.fe")
out.write_text("".join(parts))
print("wrote", out)
