"""Pack random trie vectors into a Fe module.

    python3 tools/vectors_to_fe.py fixtures/mpt/trie_vectors.json
"""
import json
import sys
from pathlib import Path
src = Path(sys.argv[1] if len(sys.argv) > 1 else "fixtures/mpt/trie_vectors.json")
d = json.loads(src.read_text())
if d.get("schema") != "verife-trie-vectors-1":
    print(f"skip {src.name}: schema {d.get('schema')!r} belongs to another generator")
    sys.exit(0)
vs = d["vectors"]
def rl(n,s_,l):
    if n<=55: return bytes([s_+n])
    be=n.to_bytes((n.bit_length()+7)//8,"big"); return bytes([l+len(be)])+be
def rs(b): return b if len(b)==1 and b[0]<0x80 else rl(len(b),0x80,0xb7)+b
def rlst(it):
    body=b"".join(it); return rl(len(body),0xc0,0xf7)+body
blob=bytearray(); blob+=len(vs).to_bytes(2,"big")
for v in vs:
    proof=rlst([rs(bytes.fromhex(n[2:])) for n in v["proof"]])
    value=bytes.fromhex(v["value"][2:]) if v["value"]!="0x" else b""
    blob+=bytes([1 if v["kind"]=="present" else 0])
    blob+=bytes.fromhex(v["root"][2:]); blob+=bytes.fromhex(v["key"][2:])
    blob+=len(value).to_bytes(2,"big"); blob+=len(proof).to_bytes(2,"big")
    blob+=value; blob+=proof
rows=[ "        "+", ".join("0x%02x"%b for b in blob[i:i+16])+"," for i in range(0,len(blob),16)]
npres=sum(1 for v in vs if v["kind"]=="present")
body=f'''//! Random Merkle-Patricia tries, for differential testing.
//!
//! Generated by `tools/gen_trie_vectors.mjs`, packed by `tools/vectors_to_fe.py`.
//! **Synthetic by design**, and labelled so: the point is to reach trie
//! *shapes* a handful of real mainnet proofs never does -- extensions of every
//! length, embedded nodes (a short value's leaf encodes to under 32 bytes and
//! is inlined in its parent), and all three kinds of absence.
//!
//! The builder is the same code that rebuilt a real block's receipts trie and
//! reproduced the `receiptsRoot` in its header, so it is a second
//! implementation, in another language, known to be right about a real trie.
//! The mainnet fixtures establish that the Fe verifier agrees with the chain;
//! these establish that it agrees with that builder across shapes.
//!
//!   {len(vs)} vectors: {npres} present, {len(vs)-npres} absent
//!   tries of {min(v["keys"] for v in vs)}..{max(v["keys"] for v in vs)} keys, proofs of {min(len(v["proof"]) for v in vs)}..{max(len(v["proof"]) for v in vs)} nodes
//!   seed 0x12345678 (xorshift32), so the set is reproducible
//!
//! The count is deliberately modest. `fe fmt` writes an array literal one
//! element per line, and compile time grows worse than linearly in that: 80
//! vectors (44 KB packed, 44,569 lines) had not finished compiling after six
//! minutes, where the whole suite without them takes 22 seconds. See
//! docs/fe-findings.md.
//!
//! Layout, integers big-endian:
//!
//! ```text
//!   u16 count
//!   per vector:  u8 present | 32 root | 32 key | u16 value_len | u16 proof_len
//!                | value | proof
//! ```

use core::ptr::MemBuffer

#[cfg(target = "native")]
pub const COUNT: usize = {len(vs)}
#[cfg(target = "native")]
pub const PRESENT: usize = {npres}
#[cfg(target = "native")]
pub const ABSENT: usize = {len(vs)-npres}

#[cfg(target = "native")]
pub fn vectors() -> MemBuffer {{
    let bytes: [u8; {len(blob)}] = [
{chr(10).join(rows)}
    ]
    var buf = MemBuffer::new(0)
    for byte in bytes {{
        buf.push(byte)
    }}
    buf
}}
'''
Path("verife/src/fixture_trie_vectors.fe").write_text(body)
print("wrote", len(blob), "bytes packed")
